import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {JSDOM}=require(process.env.JSDOM_MODULE||'jsdom');
const dom=new JSDOM(readFileSync('games/number-route/index.html','utf8'),{runScripts:'outside-only'});
const {document}=dom.window;
const gameState=document.querySelector('[data-stage]').outerHTML;
let starts=0;document.querySelector('[data-start]').addEventListener('click',()=>starts++);
dom.window.eval(readFileSync('assets/js/number-route-demo.js','utf8'));
const root=document.querySelector('[data-route-demo]');
const click=op=>root.querySelector(`[data-demo-op="${op}"]`).click();
click('+');assert.match(root.querySelector('[data-demo-feedback]').textContent,/Try again/);
assert.equal(root.querySelectorAll('[data-demo-history] li').length,0);
click('−');click('×');click('+');
assert.deepEqual([...root.querySelectorAll('[data-demo-history] li')].map(x=>x.textContent),['7 − 3 = 4','4 × 6 = 24','24 + 4 = 28']);
assert.match(root.querySelector('[data-demo-feedback]').textContent,/No points were added/);
assert.equal(root.querySelector('[data-demo-op]').disabled,true);
assert.equal(starts,0);assert.equal(document.querySelector('[data-stage]').outerHTML,gameState);
root.querySelector('[data-demo-reset]').click();
assert.equal(root.querySelectorAll('[data-demo-history] li').length,0);
assert.equal(root.querySelector('[data-demo-op]').disabled,false);
assert.match(root.querySelector('[data-demo-prompt]').textContent,/total is 7/);
console.log('Number Route practice: wrong choice, all three steps, no game start or score mutation, completion and reset passed.');
