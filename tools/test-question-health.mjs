import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(fs.readFileSync(new URL('../assets/js/question-health.js',import.meta.url),'utf8'),context);
const {assess,render}=context.window.BrainiQuestionHealth;
const row=(extra={})=>({attempts:100,correct:65,skips:0,difficulty:'medium',weak_distractor_count:0,...extra});
assert.equal(assess(null).score,null);
assert.equal(assess(row({attempts:0,correct:0})).score,null);
assert.equal(assess(row({attempts:29,correct:20})).score,null);
assert.equal(assess(row({attempts:30,correct:25,skips:5})).score,null);
assert.equal(assess(row({correct:101})).label,'Check data');
assert.equal(assess(row({correct:null})).label,'Check data');
assert.equal(assess(row({correct:92,difficulty:'easy'})).score,100);
assert.equal(assess(row({correct:30,difficulty:'hard'})).score,100);
assert.ok(assess(row({correct:10,difficulty:'easy'})).score<60);
assert.equal(assess(row({attempts:30,correct:30,difficulty:'easy'})).score,100);
assert.ok(assess(row({attempts:200,correct:198})).signals.some(s=>s.reason.includes('above')));
assert.ok(assess(row({correct:35,skips:50})).signals.some(s=>s.reason==='Frequent skips'));
assert.equal(assess(row({correct:90,difficulty:'easy',weak_distractor_count:3})).score,100);
assert.ok(assess(row({correct:65,weak_distractor_count:2})).signals.some(s=>s.reason.includes('distractors')));
assert.equal(assess(row(),{exit_rate:100,exposures:100}).score,100);
assert.equal(assess(row({difficulty:'unknown'})).score,null);
assert.ok(!render(assess(null)).includes('<meter'));
assert.ok(render(assess(row())).includes('aria-label="Question review health"'));
assert.ok(render(assess(null)).includes('Answer counts unavailable'));
console.log('Question health: 18 assertions passed.');
