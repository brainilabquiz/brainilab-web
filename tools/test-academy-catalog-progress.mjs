import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {prepareArticle,renderPage} from '../lib/learn-content.js';
import {enrichAuthors,renderLearningPage} from '../lib/learning-render.js';
const {JSDOM}=await import(pathToFileURL(process.env.JSDOM_MODULE).href);
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const authors=read('content/authors.json');
const articles=enrichAuthors(readdirSync('content/articles').map(f=>read('content/articles/'+f)).filter(a=>a.status==='published').map(prepareArticle),authors);
const paths=readdirSync('content/paths').map(f=>read('content/paths/'+f));
const template=readFileSync('learn/index.html','utf8');
const dom=new JSDOM(renderPage(template,articles,null,paths),{url:'https://brainilabgames.com/learn/#academy',runScripts:'outside-only'});
const w=dom.window,d=w.document,tick=()=>new Promise(r=>setTimeout(r,20));
const path=paths[0],first=articles.find(a=>a.slug===path.lessons[0].slug);
const card=[...d.querySelectorAll('.academy-card')].find(c=>c.querySelector('h3 a').getAttribute('href')===`/learn/paths/${path.slug}/`);
const progress=card.querySelector('[data-path-progress]');
const started=()=>progress.classList.contains('has-progress');
const store=value=>{w.localStorage.setItem('brainilab_learning_v1:guest',JSON.stringify(value));w.dispatchEvent(new w.StorageEvent('storage',{key:'brainilab_learning_v1:guest'}));};
const completion=slug=>({version:articles.find(a=>a.slug===slug).quiz.version,score:0,total:3});
const before=JSON.stringify({articles,paths});
w.eval(readFileSync('assets/js/learning-paths.bundle.js','utf8'));await tick();
assert.ok([...d.querySelectorAll('.academy-card [data-path-progress]')].every(p=>!p.classList.contains('has-progress')),'New readers have no completed course progress');
assert.equal(card.querySelector('[data-continue]').getAttribute('href'),`/learn/${first.slug}/`);
store({[first.slug]:completion(first.slug)});
assert.equal(started(),true,'A finished zero-score activity still counts as completion');
assert.match(progress.textContent,/1 of/);
assert.equal(card.querySelector('[data-continue]').getAttribute('href'),`/learn/${path.lessons[1].slug}/`);
store({[first.slug]:{...completion(first.slug),version:'outdated'}});
assert.equal(started(),false,'Old quiz versions do not show current progress');
const all=Object.fromEntries(path.lessons.map(l=>[l.slug,completion(l.slug)]));store(all);
assert.equal(started(),true);assert.equal(progress.querySelector('progress').value,100);
assert.match(card.querySelector('[data-continue]').textContent,/Revisit/);
let resolveOld;
const remote=path.lessons.slice(0,2).map(l=>({article_slug:l.slug,quiz_version:completion(l.slug).version,score:0,total:3}));
const client={from:()=>({select:()=>({eq:(_,id)=>id==='account-b'?Promise.resolve({data:remote}):new Promise(r=>resolveOld=r)})})};
w.BrainiBackendAuth={getClient:()=>client};
const auth=session=>w.dispatchEvent(new w.CustomEvent('brainilab:backend-auth',{detail:{session}}));
auth({user:{id:'account-a'}});await tick();assert.equal(started(),false,'An empty account must not display guest progress');
auth(null);await tick();assert.equal(started(),true,'Guest progress remains available after switching back');
resolveOld({data:[]});await tick();assert.equal(progress.querySelector('progress').value,100,'A late reply cannot replace the active guest display');
auth({user:{id:'account-b'}});await tick();assert.equal(started(),true);assert.match(progress.textContent,/2 of/);
assert.equal(card.querySelector('[data-continue]').getAttribute('href'),`/learn/${path.lessons[2].slug}/`);
store({});assert.match(progress.textContent,/2 of/,'A different account storage event cannot affect the active account');
auth(null);await tick();assert.equal(started(),false);
assert.equal(JSON.stringify({articles,paths}),before,'Presentation preserves content, versions and course order');
// The course page retains its full progress controls even before a quiz is completed.
const course=new JSDOM(renderLearningPage(template,{paths,articles,authors,path}));
assert.ok(course.window.document.querySelector('[data-path-progress] progress[value="0"]'));
assert.equal(course.window.document.querySelector('.learn-catalog'),null);
course.window.close();w.close();
console.log('PASS Academy catalogue: empty, partial, completed and outdated progress; zero-score completion; account isolation, stale replies, continuation links and full course controls preserved.');
