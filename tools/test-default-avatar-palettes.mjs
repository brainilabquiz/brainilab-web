import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const {JSDOM}=await import(pathToFileURL(process.env.JSDOM_MODULE).href);
const dom=new JSDOM(readFileSync('rankings/index.html','utf8'),{url:'https://brainilabgames.com/rankings/',runScripts:'outside-only'}),w=dom.window;
const names=['Cosmic Descartes','Curious Curie','Bright Hodgkin','Clever Feynman','Cosmic Avicenna','Keen Wu','Bright Maxwell','Bright Bohr'];
const rows=names.map((name,i)=>({rank:i+1,identityName:name,name,score:1000-i,level:i%2?5:8,country:''}));
const before=JSON.stringify(rows),snapshot={rows,user:null,totalPlayers:rows.length,leaderboardEnabled:true};
w.BrainiData={authState:()=>({status:'guest'}),player:()=>({xp:0,level:1})};
w.BrainiBackendAuth={isConfigured:()=>true};w.BrainiIcons={product:()=>'',groupCrest:()=>''};
w.BrainiRankingsCloud={individual:async()=>snapshot};
for(const file of ['player-personalities','avatar-design','progression-ui','rankings'])w.eval(readFileSync('assets/js/'+file+'.js','utf8'));
await new Promise(resolve=>setTimeout(resolve,0));
const UI=w.BrainiProgressUI;
const palette=row=>UI.avatarFrameAttribute(row);
assert.ok(new Set(rows.map(palette)).size>=5,'same-tier automatic identities have a useful spread of colors');
for(const row of rows){
 const value=palette(row);
 assert.match(value,/^data-default-palette="[0-7]"$/);
 assert.equal(palette({...row,rank:99,score:0,isMe:true}),value,'color cannot depend on score, rank or current user');
 assert.equal(palette({...row,level:60}),value,'identity keeps its color as its real level frame grows');
 assert.equal(palette({...row,identityName:undefined}),value,'public aliases resolve identically on social surfaces');
 assert.equal(palette({...row,avatarUrl:'https://example.test/photo.jpg'}),'','chosen photo is preserved');
 assert.equal(palette({...row,avatarDesign:{mode:'built'}}),'','created avatar is preserved');
 for(const frame of ['blue','green','copper','gold','orbit'])assert.equal(palette({...row,avatarFrame:frame}),`data-social-frame="${frame}"`,'equipped frame wins');
 assert.equal(UI.avatarImageMarkup(row),UI.defaultAvatarMarkup(row),'original portrait artwork is unchanged');
}
const legacy={name:'Guest 0123456789',level:5};
assert.equal(palette(legacy),palette({name:w.BrainiPeople.resolve(legacy).displayName,level:5}),'legacy aliases and normalized nicknames share one color');
for(const name of ['Alex','Guest friend','Guest 123','Player 42','<img src=x onerror=alert(1)>'])assert.equal(palette({name}),'','intentional names stay unchanged');
assert.equal(palette(undefined),'');
const rendered=[...w.document.querySelectorAll('.ranking-row')];
assert.equal(rendered.length,rows.length);
assert.deepEqual(rendered.map(row=>row.querySelector('.ranking-identity strong').textContent),names,'rank order stays server-provided');
assert.deepEqual(rendered.map(row=>row.querySelector('.ranking-row-score').textContent.trim()),rows.map(row=>row.score.toLocaleString()),'displayed scores stay exact');
assert.equal(w.document.querySelectorAll('.rank-avatar[data-default-palette]').length,rows.length);
const markup=rendered.map(row=>row.innerHTML);
await w.BrainiRankings.render();
assert.deepEqual([...w.document.querySelectorAll('.ranking-row')].map(row=>row.innerHTML),markup,'refresh keeps colors stable');
assert.equal(JSON.stringify(rows),before,'rendering never mutates identity, scores, level, XP or visibility');
const oldLevel=UI.avatarClass(5),newLevel=UI.avatarClass(10);
assert.notEqual(oldLevel,newLevel,'existing real tier shape progression is preserved');
const css=readFileSync('assets/css/site.css','utf8');
assert.match(css,/mask:var\(--player-frame\)/,'palette recolors the existing tier silhouette');
assert.doesNotMatch(UI.avatarImageMarkup(rows[0]),/filter|style=|data-default-palette/,'portrait itself is never color-filtered');
dom.window.close();
console.log('PASS stable default portrait palettes, useful same-level variety, legacy/social parity, custom photo/design/frame precedence, real level shape, exact score/order and no player mutation.');
