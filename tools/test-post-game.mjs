import {readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const {JSDOM}=await import(pathToFileURL(process.env.JSDOM_MODULE).href);
const dom=new JSDOM('<main id="result"></main>',{url:'https://brainilabgames.com/',runScripts:'outside-only'}),w=dom.window;
w.eval(readFileSync('assets/js/post-game.js','utf8'));
const el=w.document.querySelector('main');let shared=0;
w.BrainiShare={open:()=>shared++};
w.BrainiDailyJourney={META:{connections:{href:'games/connections/',name:'Connections',dailyQuery:true}}};
const answers=[{questionText:'Correct one',isCorrect:true,correctAnswer:'A'},{questionText:'<img src=x onerror=alert(1)>',isCorrect:false,selectedAnswer:'B',correctAnswer:'C',explanation:'<script>bad()</script>'},{questionText:'Skipped one',skipped:true,correctAnswer:'D'}];
const result={correct:1,total:3,score:450,timeSec:65,answerDetails:answers};
w.BrainiPostGame.mount(el,{result,status:{dailyIds:['brainmix','connections'],completedCount:1,games:{brainmix:{completed:true}}}});
assert.equal(el.querySelectorAll('details').length,2);
assert.equal(el.querySelector('details').open,false);
assert.equal(el.querySelectorAll('.post-answer').length,3);
assert.equal(el.querySelectorAll('script,img').length,0);
assert.match(el.querySelector('summary').textContent,/2 answers to revisit/);
assert.match(el.querySelector('.post-primary').href,/connections\/\?daily=\d{4}-\d{2}-\d{2}$/);
assert.equal(w.document.activeElement,el.querySelector('.post-score'));
el.querySelector('.post-share').click();assert.equal(shared,1);
assert.match(el.textContent,/1:05/);
w.BrainiPostGame.mount(el,{result:{...result,correct:3,answerDetails:answers.map(a=>({...a,isCorrect:true,skipped:false}))},status:{completedCount:4,dailyIds:[],games:{}}});
assert.match(el.textContent,/Every answer right/);assert.match(el.querySelector('summary').textContent,/Review your answers/);
assert.equal(el.querySelector('.post-primary').pathname,'/games/');
w.BrainiPostGame.mount(el,{result:{score:0},ads:true});assert.ok(!el.textContent.includes('undefined'));assert.equal(el.querySelectorAll('details').length,0);assert.ok(el.querySelector('[data-ad-slot]').hidden);
dom.window.close();
console.log('PASS: result review, skipped answers, perfect/missing details, XSS, keyboard focus, share, next Daily and hidden ad slot.');
